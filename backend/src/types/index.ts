/**
 * @file types/index.ts
 * @description Centralized TypeScript type definitions for the backend.
 * Includes request inputs, internal evaluation results, and complex 
 * database join interfaces.
 */

import { Request } from 'express';
import { Role, UserStatus, AttemptStatus, QuestionType } from '@prisma/client';

/**
 * Extended Express request that includes the decoded user from JWT.
 */
export interface AuthenticatedRequest extends Request {
  user?: {
    id: string;
    email: string;
    role: Role;
  };
}

/**
 * Input for the user registration endpoint.
 */
export interface RegisterInput {
  fullName: string;
  email: string;
  phone: string;
  password: string;
  nin: string;
}

/**
 * Input for the login endpoint.
 */
export interface LoginInput {
  email: string;
  password: string;
}

/**
 * Structure for creating a new exam (Admin).
 */
export interface CreateExamInput {
  title: string;
  description?: string;
  duration: number;
  maxAttempts?: number;
  passMark?: number;
  questions: CreateQuestionInput[];
}

/**
 * Structure for creating a question within an exam.
 */
export interface CreateQuestionInput {
  content: string;
  type: QuestionType;
  order: number;
  points?: number;
  imageUrl?: string;
  options?: CreateOptionInput[];
}

/**
 * Structure for creating an option for a multiple-choice question.
 */
export interface CreateOptionInput {
  content: string;
  isCorrect?: boolean;
  order: number;
  imageUrl?: string;
}

/**
 * Input required to initialize a new test attempt.
 */
export interface StartAttemptInput {
  examId: string;
}

/**
 * Input for saving an answer during an active test.
 */
export interface SaveAnswerInput {
  attemptId: string;
  questionId: string;
  selectedOptionId?: string;
  textAnswer?: string;
  wordCount?: number;
  timeSpent?: number;
  wpm?: number;
  pasteCount?: number;
}

/**
 * Input for final submission.
 */
export interface SubmitAttemptInput {
  attemptId: string;
}

/**
 * Results generated by the evaluation engine.
 */
export interface EvaluationResult {
  accuracy: number;
  grammar: number;
  plagiarism: number;
  typingSpeed: number;
  promptQuality: number;
  finalScore: number;
  passed: boolean;
}

/**
 * Specific details from a grammar analysis.
 */
export interface GrammarCheckResult {
  score: number;
  errors: Array<{
    message: string;
    offset: number;
    length: number;
  }>;
}

/**
 * Specific details from a plagiarism check.
 */
export interface PlagiarismCheckResult {
  similarityScore: number;
  matchedContent?: string;
  source?: string;
  flagged: boolean;
}

/**
 * Aggregated statistics for the user dashboard.
 */
export interface DashboardStats {
  totalAttempts: number;
  remainingAttempts: number;
  maxAttempts: number;
  status: UserStatus;
  isEligible: boolean;
  canTakeExam: boolean;
  lastAttempt?: {
    id: string;
    score: number;
    passed: boolean;
    createdAt: Date;
  };
}

/**
 * Detailed exam structure including all questions and options.
 */
export interface ExamWithQuestions {
  id: string;
  title: string;
  description: string | null;
  duration: number;
  maxAttempts: number;
  passMark: number;
  questions: Array<{
    id: string;
    content: string;
    type: QuestionType;
    order: number;
    points: number;
    options: Array<{
      id: string;
      content: string;
      order: number;
    }>;
  }>;
}

/**
 * Comprehensive attempt record including exam details, all answers, and final scores.
 */
export interface AttemptWithDetails {
  id: string;
  userId: string;
  examId: string;
  startedAt: Date;
  submittedAt: Date | null;
  status: AttemptStatus;
  timeSpent: number;
  pasteCount: number;
  tabSwitchCount: number;
  exam: {
    title: string;
    duration: number;
  };
  answers: Array<{
    id: string;
    questionId: string;
    selectedOptionId: string | null;
    textAnswer: string | null;
    wordCount: number;
    timeSpent: number;
    wpm: number;
    question: {
      content: string;
      type: QuestionType;
      points: number;
    };
  }>;
  // Fixed from singular 'score' to array 'scores' to match Prisma schema and controller logic
  scores: Array<{
    accuracy: number;
    grammar: number;
    plagiarism: number;
    typingSpeed: number;
    promptQuality: number;
    finalScore: number;
    passed: boolean;
  }>;
}

